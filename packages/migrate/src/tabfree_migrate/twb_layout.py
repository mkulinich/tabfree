"""Dashboards (zone trees, floating zones, device layouts), actions and stories."""

from __future__ import annotations

import re
from typing import Any
from urllib.parse import unquote
from xml.etree.ElementTree import Element

from tabfree_migrate.twb_xml import attrs, flag, integer, put, text_of

_TRIGGERS = {"on-select": "select", "on-hover": "hover", "on-menu": "menu", "explicit": "menu"}
_LEGENDS = {"color", "size", "shape", "map", "highlighter"}
_TSL_FIELD = re.compile(r"(\[[^\]]+\](?:\.\[[^\]]+\])*)~s0=<(\[[^>]+?\])~na>")


# --- dashboards -------------------------------------------------------------------------------------


def _zone(element: Element, floating: bool = False) -> dict[str, Any]:
    zone_type = element.get("type-v2") or element.get("type") or "viz"
    zone: dict[str, Any] = {"type": zone_type}
    for key in ("x", "y", "w", "h"):
        zone[key] = integer(element.get(key)) or 0
    put(zone, "id", element.get("id"))
    put(zone, "name", element.get("name"))
    if zone_type == "viz" or zone_type == "filter" or zone_type in _LEGENDS:
        put(zone, "worksheet", element.get("name"))
    if floating or element.get("is-floating") == "true" or element.get("floating") == "true":
        zone["floating"] = True
    if element.get("hidden-by-user") == "true" or element.get("hidden") == "true":
        zone["hidden"] = True
    if element.get("is-fixed") == "true":
        zone["fixed"] = True
    put(zone, "fixedSize", integer(element.get("fixed-size")))
    if (show := flag(element, "show-title")) is not None:
        zone["showTitle"] = show
    param = element.get("param")
    if zone_type == "layout-flow":
        layout: dict[str, Any] = {}
        if param in {"horz", "vert"}:
            layout["direction"] = param
        if element.get("layout-strategy-id") == "distribute-evenly":
            layout["distribute"] = True
        put(zone, "layout", layout)
    elif zone_type == "paramctrl":
        put(zone, "param", param)
    elif zone_type == "bitmap":
        put(zone, "image", param)
    elif zone_type == "web":
        put(zone, "url", element.get("url") or param)
    elif param:
        zone["field"] = param
    put(zone, "mode", element.get("mode"))
    put(zone, "values", element.get("values"))
    if zone_type == "text":
        put(zone, "text", text_of(element.find("formatted-text")))
    if zone_type in {"dashboard-object", "add-in"} and (addin := element.find("add-in")) is not None:
        put(zone, "extension", attrs(addin))
    put(zone, "altText", element.get("alt-text"))
    put(zone, "friendlyName", element.get("friendly-name"))
    children = element.findall("zone")
    put(zone, "children", [_zone(c) for c in children])
    style = {f.get("attr", ""): f.get("value", "") for f in element.findall("zone-style/format")}
    put(zone, "style", style)
    return zone


def _zones(element: Element) -> list[dict[str, Any]]:
    """Top-level zones. The first is the tiled layout; Tableau lists floating objects after it.

    The XML has no floating flag: a floating object is a further ``<zones>/<zone>`` sibling of the
    tiled root, positioned over it.
    """
    return [_zone(z, floating=i > 0) for i, z in enumerate(element.findall("zones/zone"))]


def _size(element: Element | None) -> dict[str, Any]:
    info: dict[str, Any] = {}
    if element is None:
        return info
    mode = element.get("sizing-mode")
    if mode in {"fixed", "range", "automatic", "vscroll"}:
        info["mode"] = mode
    for attr, key in (
        ("maxwidth", "width"), ("maxheight", "height"), ("minwidth", "minWidth"),
        ("minheight", "minHeight"), ("maxwidth", "maxWidth"), ("maxheight", "maxHeight"),
    ):  # fmt: skip
        if (value := integer(element.get(attr))) is not None:
            info[key] = value
    return info


def dashboard(element: Element) -> dict[str, Any]:
    dash: dict[str, Any] = {"name": element.get("name", ""), "zones": []}
    title = element.find("layout-options/title")
    if title is not None:
        put(dash, "title", text_of(title))
    put(dash, "size", _size(element.find("size")))
    dash["zones"] = _zones(element)
    layouts = []
    for device in element.findall("devicelayouts/devicelayout"):
        name = device.get("name") or ""
        kind = "phone" if "phone" in name.lower() else "tablet" if "tablet" in name.lower() else "desktop"
        entry: dict[str, Any] = {"device": kind, "zones": _zones(device)}
        put(entry, "name", name)
        put(entry, "size", _size(device.find("size")))
        if device.get("auto-generated") == "true":
            entry["autoGenerated"] = True
        layouts.append(entry)
    put(dash, "deviceLayouts", layouts)
    return dash


# --- actions -----------------------------------------------------------------------------------------


def _command_type(command: str) -> str:
    if "tsl-filter" in command or command.endswith(":filter"):
        return "filter"
    if "brush" in command or "highlight" in command:
        return "highlight"
    if "goto" in command or "navigate" in command:
        return "sheet-navigate"
    if "url" in command or "browse" in command or "link" in command:
        return "url"
    if "parameter" in command:
        return "edit-parameter"
    if "group" in command or "set" in command:
        return "edit-group"
    return "unknown"


def _names(value: str | None) -> list[str]:
    return [v for v in (value or "").split(",") if v]


def _link_fields(expression: str) -> list[dict[str, str]]:
    """Source → target field pairs encoded in a filter action's ``tsl:`` link."""
    return [
        {"source": source, "target": target} for target, source in _TSL_FIELD.findall(unquote(expression))
    ]


def action(element: Element) -> dict[str, Any]:
    """An ``<action>``, ``<nav-action>``, ``<edit-group-action>`` or ``<edit-parameter-action>``."""
    command_el = element.find("command")
    link = element.find("link")
    command = command_el.get("command", "") if command_el is not None else ""
    if element.tag == "edit-group-action":
        kind = "edit-group"
    elif element.tag == "edit-parameter-action":
        kind = "edit-parameter"
    elif element.tag == "nav-action":
        kind = "sheet-navigate"
    elif link is not None and not command:
        kind = "url"
    else:
        kind = _command_type(command)
    act: dict[str, Any] = {"name": element.get("name", ""), "type": kind}
    put(act, "caption", element.get("caption"))
    activation = element.find("activation")
    clear: dict[str, Any] = {}
    if activation is not None:
        if activation.get("type") in _TRIGGERS:
            act["trigger"] = _TRIGGERS[str(activation.get("type"))]
        if (auto := flag(activation, "auto-clear")) is not None:
            clear["autoClear"] = auto
    source = element.find("source")
    if source is not None:
        src: dict[str, Any] = {}
        put(src, "type", source.get("type"))
        put(src, "dashboard", source.get("dashboard"))
        put(src, "datasource", source.get("datasource"))
        sheets = [source.get("worksheet", "")] if source.get("worksheet") else []
        put(src, "worksheets", sheets + [s.get("name", "") for s in source.findall("worksheet")])
        put(src, "excludeSheets", [s.get("name", "") for s in source.findall("exclude-sheet")])
        put(act, "source", src)
    put(act, "command", command)
    param_els = element.findall("command/param") + element.findall("params/param")
    params = {p.get("name", ""): p.get("value", "") for p in param_els}
    target: dict[str, Any] = {}
    put(target, "name", params.get("target"))
    put(target, "excludeSheets", _names(params.get("exclude")))
    put(target, "parameter", params.get("target-parameter"))
    put(target, "set", params.get("target-group"))
    fields: list[dict[str, str]] = []
    if link is not None:
        expression = link.get("expression", "")
        if kind == "url":
            put(target, "url", expression)
        else:
            fields += _link_fields(expression)
        info: dict[str, Any] = {"expression": expression}
        put(info, "caption", link.get("caption"))
        for attr, key in (("multi-select", "multiSelect"), ("include-null", "includeNull"),
                          ("url-escape", "urlEscape")):  # fmt: skip
            if (value := flag(link, attr)) is not None:
                info[key] = value
        put(info, "delimiter", link.get("delimiter"))
        put(info, "escape", link.get("escape"))
        put(info, "target", text_of(link.find("url-action-type")))
        act["link"] = info
    if source_field := params.get("source-field"):
        fields.append({"source": source_field, "target": params.get("target-parameter", "")})
    put(act, "fields", fields)
    if params.get("special-fields") == "all":
        act["allFields"] = True
    put(act, "fieldCaptions", _names(params.get("field-captions")))
    put(act, "target", target)
    put(clear, "onEmpty", params.get("on-empty"))
    put(clear, "setOption", params.get("selection-clear-set-option"))
    if (clear_option := element.find("clear-option")) is not None:
        put(clear, "option", clear_option.get("type"))
        put(clear, "value", clear_option.get("value"))
    put(act, "clear", clear)
    if (marks := element.find("add-or-remove-marks")) is not None:
        put(act, "setMode", marks.get("value"))
    if (agg := element.find("agg-type")) is not None:
        put(act, "aggregation", agg.get("type"))
    if (single := element.find("single-select")) is not None and flag(single, "value") is not None:
        act["singleSelect"] = flag(single, "value")
    put(act, "params", params)
    return act


def resolve_targets(actions: list[dict[str, Any]], dashboards: set[str], sheets: set[str]) -> None:
    """Turn each action's target ``name`` into a dashboard or worksheet now that all are known."""
    for act in actions:
        target = act.get("target", {})
        name = target.pop("name", None)
        if name is None:
            continue
        if name in dashboards:
            target["dashboard"] = name
        elif name in sheets:
            target["worksheets"] = [name]
        else:
            target["sheet"] = name


# --- stories -----------------------------------------------------------------------------------------


def story(element: Element) -> dict[str, Any]:
    entry: dict[str, Any] = {"name": element.get("name", ""), "points": []}
    title = element.find("layout-options/title")
    if title is not None:
        put(entry, "title", text_of(title))
    put(entry, "size", _size(element.find("size")))
    flipboard = element.find(".//flipboard")
    if flipboard is not None:
        put(entry, "navigation", flipboard.get("nav-type"))
    for point in element.iter("story-point"):
        item: dict[str, Any] = {}
        put(item, "id", point.get("id"))
        put(item, "caption", point.get("caption"))
        put(item, "target", point.get("captured-sheet"))
        state: dict[str, Any] = {}
        deltas = point.find("capturedDeltas")
        if deltas is not None:
            for tag, key in (("worksheet", "worksheets"), ("dashboard", "dashboards"),
                             ("datasource", "datasources")):  # fmt: skip
                put(state, key, [d.get("name", "") for d in deltas.findall(tag)])
        put(item, "state", state)
        entry["points"].append(item)
    return entry
